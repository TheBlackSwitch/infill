export class selection {
    #start_position: number = 0;
    #end_position: number = 0;
    #parent_element: HTMLElement | undefined;

    constructor(start: number, end: number) {
        this.#start_position = start;
        this.#end_position = end;
    }

    // Apply the selection to a certain position
    apply(parent: HTMLElement, selection_layer: HTMLElement) {
        this.#parent_element = parent;
    }


    #update_mark() {
        if(this.#parent_element === undefined) return;

    }
}